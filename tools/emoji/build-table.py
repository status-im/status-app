#!/usr/bin/env python3
"""Build the C++ emoji table StatusEmojiModel serves from emojiList.json.

The table is plain read-only data (no pointers, so no relocations): the OS maps
it from the binary and can drop the pages again while nobody looks at emoji,
instead of the app parsing 1.7 MB of json onto the heap at login.

Usage:
    build-table.py            write ui/StatusQ/src/emojitable_data.cpp
    build-table.py --check    regenerate in memory and diff; non-zero on drift
"""
import argparse
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(REPO, "ui/StatusQ/src/emojitable_data.cpp")

_spec = importlib.util.spec_from_file_location(
    "build_catalogue", os.path.join(HERE, "build-catalogue.py"))
bc = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(bc)

# EmojiTable::Entry::skin: 0 no skins, 1 base of toned variants, 2.. this tone
TONES = ["1f3fb", "1f3fc", "1f3fd", "1f3fe", "1f3ff"]


class Pool:
    """NUL-terminated UTF-8 strings, each stored once."""

    def __init__(self):
        self.blob = bytearray()
        self.offsets = {}

    def ref(self, text):
        if text not in self.offsets:
            self.offsets[text] = len(self.blob)
            self.blob += text.encode("utf-8") + b"\0"
        return self.offsets[text]


class Lists:
    """Lists of strings as a count followed by string refs, each stored once."""

    def __init__(self, pool):
        self.pool = pool
        self.words = [0]  # the shared empty list
        self.offsets = {(): 0}

    def ref(self, items):
        key = tuple(items)
        if key not in self.offsets:
            self.offsets[key] = len(self.words)
            self.words += [len(items)] + [self.pool.ref(i) for i in items]
        return self.offsets[key]


def skin_of(row):
    # first tone in TONES order, as StatusEmojiModel always reported it
    for i, tone in enumerate(TONES):
        if tone in row["unicode"]:
            return 2 + i
    return 1 if row["hasSkins"] else 0


def comment(text):
    return text.replace("*/", "* /").replace("/*", "/ *")


def generate(rows):
    if len(rows) >= 0xFFFF:
        sys.exit("ERROR: entry indices no longer fit in 16 bits")
    flags = [i for i, r in enumerate(rows) if r["category"] == "flags"]
    if not flags or flags[-1] != len(rows) - 1:
        sys.exit("ERROR: flags must be the last block")

    pool = Pool()
    lists = Lists(pool)
    entries = []
    for r in rows:
        if r["category"] not in bc.CATEGORIES:
            sys.exit(f"ERROR: unknown category {r['category']}")
        if r["hasSkins"] and skin_of(r) != 1:
            sys.exit(f"ERROR: {r['unicode']} has skins but carries a tone")
        entries.append((
            pool.ref(r["emoji"]), pool.ref(r["unicode"]),
            pool.ref(bc.canonical(r["unicode"])), pool.ref(r["name"]),
            pool.ref(r["shortname"]), lists.ref(r["aliases"]),
            lists.ref(r["aliases_ascii"]), lists.ref(r["keywords"]),
            r["emoji_order"], bc.CATEGORIES.index(r["category"]), skin_of(r)))
        if r["emoji_order"] > 0xFFFF:
            sys.exit(f"ERROR: {r['unicode']} order does not fit in 16 bits")

    def sorted_by(key):
        return sorted(range(len(rows)), key=lambda i: key(rows[i]).encode("utf-8"))

    ascii_aliases = {}
    for i, r in enumerate(rows):
        for alias in r["aliases_ascii"]:
            if not alias.isascii():
                sys.exit(f"ERROR: emoticon {alias!r} is not ascii")
            ascii_aliases.setdefault(alias, i)  # first occurrence wins
            pool.ref(alias)
    category_start = [next(i for i, r in enumerate(rows) if r["category"] == c)
                      for c in bc.CATEGORIES]

    out = ["// Generated by tools/emoji/build-table.py from emojiList.json. Do not edit.",
           "// clang-format off",
           '#include "emojitable.h"',
           "",
           "namespace EmojiTable {",
           "",
           f"const std::uint16_t entryCount = {len(rows)};",
           f"const std::uint16_t firstFlagEntry = {flags[0]};",
           f"const std::uint16_t maxAsciiAliasLength = "
           f"{max((len(a) for a in ascii_aliases), default=0)};",
           f"const std::uint16_t asciiAliasCount = {len(ascii_aliases)};",
           "",
           "const unsigned char strings[] = {"]
    # Bytes, not a string literal: MSVC caps a literal at 64 KB.
    for text in pool.offsets:
        out.append("    " + "".join(f"{b}," for b in text.encode("utf-8")) + "0,")
    out.append("};")
    out.append("")
    out.append("const std::uint32_t lists[] = {")
    for i in range(0, len(lists.words), 16):
        out.append("    " + ",".join(str(w) for w in lists.words[i:i + 16]) + ",")
    out.append("};")
    out.append("")
    out.append("const Entry entries[] = {")
    for r, e in zip(rows, entries):
        out.append("    {" + ",".join(str(v) for v in e) + "}, "
                   f"/* {r['unicode']} {comment(r['shortname'])} */")
    out.append("};")
    for name, key in (("byUnicode", lambda r: r["unicode"]),
                      ("byCanonical", lambda r: bc.canonical(r["unicode"])),
                      ("byShortname", lambda r: r["shortname"])):
        order = sorted_by(key)
        out.append("")
        out.append(f"const std::uint16_t {name}[] = {{")
        for i in range(0, len(order), 16):
            out.append("    " + ",".join(str(v) for v in order[i:i + 16]) + ",")
        out.append("};")
    out.append("")
    out.append("const AsciiAlias asciiAliases[] = {")
    for alias in sorted(ascii_aliases, key=lambda a: a.encode("utf-8")):
        out.append(f"    {{{pool.ref(alias)}, {ascii_aliases[alias]}}}, /* {comment(alias)} */")
    out.append("};")
    out.append("")
    out.append("const std::uint16_t categoryStart[] = {"
               + ", ".join(str(s) for s in category_start) + "};")
    out.append("")
    out.append("} // namespace EmojiTable")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="do not write; fail if the committed table differs")
    parser.add_argument("--catalogue", default=bc.CATALOGUE)
    parser.add_argument("--out", default=OUT)
    args = parser.parse_args()

    with open(args.catalogue, encoding="utf-8") as f:
        text = generate(json.load(f))

    if args.check:
        current = ""
        if os.path.exists(args.out):
            with open(args.out, encoding="utf-8") as f:
                current = f.read()
        if current != text:
            print(f"DRIFT: {os.path.relpath(args.out, REPO)} is not what "
                  f"{os.path.relpath(args.catalogue, REPO)} produces")
            return 1
        return 0

    with open(args.out, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(args.out, REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
